let lang = 'zh';
export function setLang(l) { lang = l === 'en' ? 'en' : 'zh'; document.documentElement.lang = lang === 'zh' ? 'zh-Hant-TW' : 'en'; }
export function getLang() { return lang; }
export function t(key, params = {}) {
  let s = STR[lang][key] ?? STR.zh[key] ?? key;
  if (typeof s !== 'string') return s;
  for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, v);
  return s;
}
// pick from a {zh, en} object
export function L(obj) { return obj ? (obj[lang] ?? obj.zh) : ''; }
export function fmtCoins(n) { return Number.isInteger(n) ? String(n) : n.toFixed(1); }
export function fmtTime(ts) {
  const d = new Date(ts);
  return `${String(d.getHours()).padStart(2, '0')}:${String(d.getMinutes()).padStart(2, '0')}`;
}
export function fmtDay(key) {
  const [y, m, d] = key.split('-').map(Number);
  if (lang === 'zh') return `${m} 月 ${d} 日`;
  return new Date(y, m - 1, d).toLocaleDateString('en', { month: 'short', day: 'numeric' });
}
